#!/usr/bin/env python3
"""Refresh read-only prototype inputs through the course's supported query CLI."""
import json
import pathlib
import subprocess

here = pathlib.Path(__file__).resolve().parent
project = here.parents[1]
root = project / "courses/digital-logic"
cli = ["python3", str(root / "期中/工具/知识地图.py")]

def query(*args):
    return json.loads(subprocess.check_output(cli + list(args), cwd=root, text=True))

graph = query("graph", "--view", "all")
primary_ids = ["KU-035", "KU-055", "KU-056", "KU-063"]
edges = [e for e in graph["edges"] if e["fromUnitId"] in primary_ids or e["toUnitId"] in primary_ids]
ids = set(primary_ids)
for edge in edges:
    ids.update([edge["fromUnitId"], edge["toUnitId"]])
units = [query("get", ident) for ident in sorted(ids)]
theme_ids = {unit["themeId"] for unit in units}
sources = {ref["sourceId"] for unit in units for ref in unit.get("sourceRefs", [])}
data = {
    "sourceHash": graph["sourceHash"],
    "primaryIds": primary_ids,
    "units": units,
    "themes": [t for t in graph["groups"] if t["id"] in theme_ids],
    "edges": edges,
    "sources": [query("get", ident) for ident in sorted(sources)],
}
(here / "course-data.js").write_text("// Generated by export-data.py; do not edit course facts here.\nwindow.COURSE_DATA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n")
rough_source = here.parent / "style-math-prototype/vendor/roughjs/rough.cjs.js"
(here / "rough-browser.js").write_text("/* Rough.js 4.6.6, MIT; browser wrapper for the existing local dependency. */\n(function(){const module={exports:{}};\n" + rough_source.read_text() + "\nwindow.rough=module.exports;})();\n")
print(f"Exported {len(units)} units, {len(data['themes'])} themes, {len(edges)} reviewed relations.")
